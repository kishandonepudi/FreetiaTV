// Release signing: CI passes FREETIA_* env vars; locally an untracked keystore.properties works too. With neither,
// release builds are unsigned (fine for bundleStoreRelease checks; Play needs the bundle signed with the upload key).
val keystoreProps = Properties().apply {
    rootProject.file("keystore.properties").takeIf { it.isFile }?.inputStream()?.use { load(it) }
}
fun signingValue(env: String, prop: String): String? = System.getenv(env) ?: keystoreProps.getProperty(prop)
val releaseKeystore: String? = signingValue("FREETIA_KEYSTORE_PATH", "storeFile")

